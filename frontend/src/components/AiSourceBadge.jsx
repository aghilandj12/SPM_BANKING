import React from 'react';

const PROVIDER_NAMES = { gemini: 'Gemini', groq: 'Groq' };

// Shows whether a result came from an AI model or from the rule-based fallback
// the backend returns when every AI provider failed.
export default function AiSourceBadge({ provider, block = false }) {
  if (!provider) return null;

  if (provider === 'deterministic_fallback') {
    const text = 'AI unavailable: this is a rule-based template, not an AI analysis. Try again shortly.';
    return block
      ? <div className="ai-source-fallback">{text}</div>
      : <span className="badge badge-medium" title={text}>Fallback · not AI</span>;
  }

  const name = PROVIDER_NAMES[provider] || provider;
  return <span className="badge badge-low" title={`Generated by ${name}`}>AI-generated · {name}</span>;
}
